begin;
create table public.words (
 id bigint generated by default as identity primary key, word text not null unique,
 ipa text, pos text, meaning_vi text, example text, topic text, order_index integer not null
);
create table public.study_sessions (
 id uuid primary key default gen_random_uuid(), user_id uuid not null references auth.users(id) on delete cascade,
 date date not null default (now() at time zone 'Asia/Ho_Chi_Minh')::date,
 words_studied integer not null default 0 check(words_studied>=0), correct integer not null default 0 check(correct>=0), wrong integer not null default 0 check(wrong>=0),
 duration_sec integer not null default 0 check(duration_sec>=0), completed_at timestamptz, created_at timestamptz not null default now()
);
create table public.user_word_progress (
 user_id uuid not null references auth.users(id) on delete cascade, word_id bigint not null references public.words(id),
 status text not null default 'new' check(status in ('new','learning','mastered')),
 ease_factor double precision not null default 2.5 check(ease_factor>=1.3), interval_days integer not null default 0 check(interval_days>=0), repetitions integer not null default 0 check(repetitions>=0),
 first_reviewed_at timestamptz, next_review_at timestamptz, correct_count integer not null default 0 check(correct_count>=0), wrong_count integer not null default 0 check(wrong_count>=0),
 correct_streak integer not null default 0 check(correct_streak>=0), in_mistakes boolean not null default false, last_wrong_at timestamptz, last_reviewed_at timestamptz,
 last_correct_session_id uuid references public.study_sessions(id), primary key(user_id,word_id)
);
create table public.mistake_log (
 id uuid primary key default gen_random_uuid(), user_id uuid not null references auth.users(id) on delete cascade,
 word_id bigint not null references public.words(id), mode text not null check(mode in ('flashcard','quiz_meaning','quiz_fill','quiz_listen')),
 user_answer text, created_at timestamptz not null default now()
);
create table public.user_settings (
 user_id uuid primary key references auth.users(id) on delete cascade,
 new_words_per_day integer not null default 15 check(new_words_per_day between 1 and 100),
 tts_enabled boolean not null default true, theme text not null default 'light' check(theme in ('light','dark'))
);
create table public.review_events (
 id uuid primary key, user_id uuid not null references auth.users(id) on delete cascade,
 session_id uuid not null references public.study_sessions(id) on delete cascade, word_id bigint not null references public.words(id),
 mode text not null check(mode in ('flashcard','quiz_meaning','quiz_fill','quiz_listen')), rating integer not null check(rating in (0,3,4,5)), user_answer text,
 created_at timestamptz not null default clock_timestamp()
);
create index progress_due on public.user_word_progress(user_id,next_review_at);
create index sessions_owner_date on public.study_sessions(user_id,date);
create index events_session_word on public.review_events(session_id,word_id);
create index mistakes_owner_time on public.mistake_log(user_id,created_at desc);
alter table public.words enable row level security;
create policy words_authenticated_read on public.words for select to authenticated using (true);
do $$ declare t text; begin
 foreach t in array array['user_word_progress','study_sessions','mistake_log','user_settings','review_events'] loop
 execute format('alter table public.%I enable row level security',t);
 execute format('create policy owner_read on public.%I for select to authenticated using (user_id = (select auth.uid()))',t);
 end loop;
end $$;
create policy settings_owner_insert on public.user_settings for insert to authenticated with check(user_id=(select auth.uid()));
create policy settings_owner_update on public.user_settings for update to authenticated using(user_id=(select auth.uid())) with check(user_id=(select auth.uid()));
revoke all on public.words,public.user_word_progress,public.study_sessions,public.mistake_log,public.user_settings,public.review_events from anon,authenticated;
grant select on public.words,public.user_word_progress,public.study_sessions,public.mistake_log,public.user_settings,public.review_events to authenticated;
grant insert,update on public.user_settings to authenticated;

create function public.start_study_session() returns public.study_sessions
language plpgsql security definer set search_path = '' as $$
declare s public.study_sessions; u uuid := auth.uid();
begin
 if u is null then raise insufficient_privilege using message='Authentication required'; end if;
 insert into public.study_sessions(user_id) values(u) returning * into s;
 return s;
end $$;

create function public.record_study_answer(p_session_id uuid,p_word_id bigint,p_mode text,p_rating int,p_user_answer text,p_event_id uuid) returns void
language plpgsql security definer set search_path = '' as $$
declare u uuid := auth.uid(); s public.study_sessions; p public.user_word_progress; e public.review_events; days integer; reps integer; ef double precision; fresh boolean;
begin
 if u is null then raise insufficient_privilege using message='Authentication required'; end if;
 if length(p_user_answer)>1000 then raise exception 'Answer too long'; end if;
 if p_mode is null or p_mode not in ('flashcard','quiz_meaning','quiz_fill','quiz_listen') or p_rating is null or p_rating not in (0,3,4,5) or p_event_id is null or p_word_id is null then raise exception 'Invalid answer'; end if;
 -- Per-user locking serializes answer, finish and manual mistake changes across sessions.
 perform pg_catalog.pg_advisory_xact_lock(pg_catalog.hashtextextended(u::text,0));
 select * into s from public.study_sessions where id=p_session_id and user_id=u for update;
 if not found then raise insufficient_privilege using message='Session unavailable'; end if;
 select * into e from public.review_events where id=p_event_id;
 if found then
  if e.user_id=u and e.session_id=p_session_id and e.word_id=p_word_id and e.mode=p_mode and e.rating=p_rating and e.user_answer is not distinct from p_user_answer then return; end if;
  raise exception 'Event id already used';
 end if;
 if s.completed_at is not null then raise exception 'Session already completed'; end if;
 insert into public.user_word_progress(user_id,word_id) values(u,p_word_id) on conflict do nothing;
 select * into p from public.user_word_progress where user_id=u and word_id=p_word_id for update;
 fresh := not exists(select 1 from public.review_events where session_id=p_session_id and word_id=p_word_id);
 insert into public.review_events(id,user_id,session_id,word_id,mode,rating,user_answer) values(p_event_id,u,p_session_id,p_word_id,p_mode,p_rating,p_user_answer);
 ef := greatest(1.3,p.ease_factor + 0.1 - (5-p_rating)*(0.08+(5-p_rating)*0.02));
 if p_rating=0 then reps:=0; days:=1;
 else
  days := case p.repetitions when 0 then 1 when 1 then 6 else greatest(1,round(p.interval_days*p.ease_factor)::integer) end;
  reps := p.repetitions+1;
 end if;
 update public.user_word_progress set ease_factor=ef, interval_days=days,repetitions=reps,
 status=case when reps>=3 then 'mastered' else 'learning' end,
 next_review_at=now()+pg_catalog.make_interval(days=>days), last_reviewed_at=now(), first_reviewed_at=coalesce(first_reviewed_at,now()),
 correct_count=correct_count+case when p_rating>=3 then 1 else 0 end,
 wrong_count=wrong_count+case when p_rating=0 then 1 else 0 end,
 correct_streak=case when p_rating=0 then 0 else correct_streak end,
 in_mistakes=case when p_rating=0 then true else in_mistakes end,
 last_wrong_at=case when p_rating=0 then clock_timestamp() else last_wrong_at end
 where user_id=u and word_id=p_word_id;
 if p_rating=0 then insert into public.mistake_log(user_id,word_id,mode,user_answer) values(u,p_word_id,p_mode,p_user_answer); end if;
 update public.study_sessions set words_studied=words_studied+fresh::integer,correct=correct+case when p_rating>=3 then 1 else 0 end,wrong=wrong+case when p_rating=0 then 1 else 0 end where id=p_session_id;
end $$;

create function public.finish_study_session(p_session_id uuid,p_duration_sec int) returns void
language plpgsql security definer set search_path = '' as $$
declare u uuid:=auth.uid(); s public.study_sessions;
begin
 if u is null then raise insufficient_privilege using message='Authentication required'; end if;
 if p_duration_sec is null or p_duration_sec<0 or p_duration_sec>86400 then raise exception 'Invalid duration'; end if;
 perform pg_catalog.pg_advisory_xact_lock(pg_catalog.hashtextextended(u::text,0));
 select * into s from public.study_sessions where id=p_session_id and user_id=u for update;
 if not found then raise insufficient_privilege using message='Session unavailable'; end if;
 if s.completed_at is not null then return; end if;
 if s.words_studied=0 then raise exception 'Cannot finish an empty session'; end if;
 update public.user_word_progress p set correct_streak=p.correct_streak+1,
 in_mistakes=case when p.correct_streak+1>=3 then false else p.in_mistakes end,last_correct_session_id=p_session_id
 where p.user_id=u and exists(
  select 1 from public.review_events e where e.session_id=p_session_id and e.word_id=p.word_id group by e.word_id
  having bool_and(e.rating>=3)
  -- A wrong answer in another overlapping session also breaks this session's eligibility.
  and min(e.created_at)>coalesce(p.last_wrong_at,'-infinity'::timestamptz)
 );
 update public.study_sessions set completed_at=now(),duration_sec=p_duration_sec where id=p_session_id;
end $$;

create function public.set_word_mistake(p_word_id bigint,p_marked boolean) returns void
language plpgsql security definer set search_path = '' as $$
declare u uuid:=auth.uid();
begin
 if u is null then raise insufficient_privilege using message='Authentication required'; end if;
 if p_marked is null then raise exception 'Marked is required'; end if;
 perform pg_catalog.pg_advisory_xact_lock(pg_catalog.hashtextextended(u::text,0));
 insert into public.user_word_progress(user_id,word_id,in_mistakes) values(u,p_word_id,p_marked)
 on conflict(user_id,word_id) do update set in_mistakes=p_marked,correct_streak=0;
end $$;
revoke all on function public.start_study_session(),public.record_study_answer(uuid,bigint,text,int,text,uuid),public.finish_study_session(uuid,int),public.set_word_mistake(bigint,boolean) from public,anon;
grant execute on function public.start_study_session(),public.record_study_answer(uuid,bigint,text,int,text,uuid),public.finish_study_session(uuid,int),public.set_word_mistake(bigint,boolean) to authenticated;
commit;
